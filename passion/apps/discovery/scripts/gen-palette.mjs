// Emits app/palette.generated.ts: 8 fills at a single OKLCH lightness+chroma, hues rotated.
// Equal L and C is the whole measurement point — only hue changes, so no fill is "brighter".
// Self-contained OKLCH -> linear sRGB -> gamma, no dependency.
// Chroma is the MAX value that remains in-gamut for ALL 8 hues at L=0.72.
const L = 0.72;
const HUES = [25, 60, 110, 150, 200, 255, 300, 340];

function oklchToLinearRgb(l, c, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = l - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const [L3, M3, S3] = [l_ ** 3, m_ ** 3, s_ ** 3];
  return [
    +4.0767416621 * L3 - 3.3077115913 * M3 + 0.2309699292 * S3,
    -1.2684380046 * L3 + 2.6097574011 * M3 - 0.3413193965 * S3,
    -0.0041960863 * L3 - 0.7034186147 * M3 + 1.707614701 * S3,
  ];
}

function getMaxInGamutChromaForHue(l, hDeg) {
  // Binary search for the maximum chroma that keeps all linear RGB channels in [0, 1].
  let cLow = 0;
  let cHigh = 0.4;
  for (let i = 0; i < 50; i++) {
    const cMid = (cLow + cHigh) / 2;
    const lin = oklchToLinearRgb(l, cMid, hDeg);
    const inGamut = lin.every((x) => x >= -1e-5 && x <= 1 + 1e-5);
    if (inGamut) {
      cLow = cMid;
    } else {
      cHigh = cMid;
    }
  }
  return cLow;
}

// Find max in-gamut chroma for each hue, then take the minimum across all hues.
const maxCharmasPerHue = HUES.map((h) => getMaxInGamutChromaForHue(L, h));
const minMaxChroma = Math.min(...maxCharmasPerHue);
const sharedChroma = minMaxChroma * 0.995; // Apply 0.995 safety margin.

// Verify the result is vivid enough.
if (sharedChroma < 0.11) {
  throw new Error(
    `Shared chroma ${sharedChroma.toFixed(5)} is too dull (< 0.11). ` +
      `Max chromas per hue: [${maxCharmasPerHue.map((c) => c.toFixed(5)).join(", ")}]`,
  );
}

function oklchToRgb(l, c, hDeg) {
  const lin = oklchToLinearRgb(l, c, hDeg);
  // Final assertion: no linear RGB channel should need hard clamping.
  for (let i = 0; i < lin.length; i++) {
    if (lin[i] < -1e-5 || lin[i] > 1 + 1e-5) {
      throw new Error(
        `Hue ${hDeg}: linear RGB[${i}] = ${lin[i]} is out of gamut. ` + `Chroma ${c} is too high.`,
      );
    }
  }
  const g = (x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
    return Math.max(0, Math.min(1, v));
  };
  return lin.map((x) => Math.round(g(x) * 255));
}

const hex = ([r, g, b]) => `#${[r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
const fills = HUES.map((h) => hex(oklchToRgb(L, sharedChroma, h)));

// Emit the FILLS array one-entry-per-line so the generated file matches biome's formatter (a
// single-line array would be reflowed on the next `pnpm lint`, drifting the committed output).
const fillsBlock = `[\n${fills.map((f) => `  "${f}",`).join("\n")}\n]`;

process.stdout.write(
  `// GENERATED by scripts/gen-palette.mjs — do not edit by hand.\n// 8 fills at OKLCH L=${L} C=${sharedChroma.toFixed(5)}, hues ${JSON.stringify(HUES)}.\nexport const STROKE = "#002a3a";\nexport const HIGHLIGHT = "#fcf4ef";\nexport const STROKE_WIDTH = 9;\nexport const FILLS = ${fillsBlock} as const;\nexport const ALLOWED_FILLS: ReadonlySet<string> = new Set([...FILLS, "#ffffff", HIGHLIGHT]);\n`,
);
